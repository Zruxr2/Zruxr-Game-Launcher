const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('launcher', {
  getLibrary: () => ipcRenderer.invoke('library:get'),
  pickGameFile: () => ipcRenderer.invoke('dialog:pickGameFile'),
  pickCover: () => ipcRenderer.invoke('dialog:pickCover'),
  addGame: (data) => ipcRenderer.invoke('game:add', data),
  updateGame: (data) => ipcRenderer.invoke('game:update', data),
  removeGame: (id) => ipcRenderer.invoke('game:remove', id),
  launch: (id) => ipcRenderer.invoke('game:launch', id),
  stop: (id) => ipcRenderer.invoke('game:stop', id),
  showInFolder: (id) => ipcRenderer.invoke('game:showInFolder', id),
  toggleFavorite: (id) => ipcRenderer.invoke('game:favorite', id),
  onLibraryChanged: (cb) => ipcRenderer.on('library:changed', (_e, games) => cb(games)),

  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  getAppInfo: () => ipcRenderer.invoke('app:info'),
  openDataFolder: () => ipcRenderer.invoke('app:openDataFolder'),
  refreshCovers: () => ipcRenderer.invoke('covers:refreshMissing'),

  getAccount: () => ipcRenderer.invoke('account:get'),
  signIn: (data) => ipcRenderer.invoke('account:signIn', data),
  signUp: (data) => ipcRenderer.invoke('account:signUp', data),
  signOut: () => ipcRenderer.invoke('account:signOut'),
  syncNow: () => ipcRenderer.invoke('account:sync'),
  scanRun: (mode) => ipcRenderer.invoke('scan:run', mode),
  scanCancel: () => ipcRenderer.invoke('scan:cancel'),
  scanAdd: (paths) => ipcRenderer.invoke('scan:add', paths),
  onScanProgress: (cb) => ipcRenderer.on('scan:progress', (_e, p) => cb(p)),
  discoverGet: (force) => ipcRenderer.invoke('discover:get', !!force),
  discoverOpen: (id) => ipcRenderer.invoke('discover:open', id),
  getProfile: () => ipcRenderer.invoke('profile:get'),
  pickAvatar: () => ipcRenderer.invoke('profile:pickAvatar'),
  removeAvatar: () => ipcRenderer.invoke('profile:removeAvatar'),
  onAccountChanged: (cb) => ipcRenderer.on('account:changed', (_e, state) => cb(state)),
  getUpdate: () => ipcRenderer.invoke('update:state'),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  onUpdate: (cb) => ipcRenderer.on('update:status', (_e, s) => cb(s)),
  sourcesList: () => ipcRenderer.invoke('sources:list'),
  sourcesAdd: (url) => ipcRenderer.invoke('sources:add', url),
  sourcesRefresh: (id) => ipcRenderer.invoke('sources:refresh', id),
  sourcesRemove: (id) => ipcRenderer.invoke('sources:remove', id),
  sourcesItems: () => ipcRenderer.invoke('sources:items'),
  sourceCover: (title) => ipcRenderer.invoke('sources:cover', title),
  downloadsList: () => ipcRenderer.invoke('downloads:list'),
  downloadStart: (req) => ipcRenderer.invoke('downloads:start', req),
  downloadPause: (id) => ipcRenderer.invoke('downloads:pause', id),
  downloadResume: (id) => ipcRenderer.invoke('downloads:resume', id),
  downloadRemove: (id) => ipcRenderer.invoke('downloads:remove', id),
  downloadShow: (id) => ipcRenderer.invoke('downloads:show', id),
  downloadPrepareGame: (id) => ipcRenderer.invoke('downloads:prepareGame', id),
  downloadDir: () => ipcRenderer.invoke('downloads:dir'),
  downloadPickDir: () => ipcRenderer.invoke('downloads:pickDir'),
  downloadPickDirFor: () => ipcRenderer.invoke('downloads:pickDirFor'),
  downloadFocus: (id) => ipcRenderer.invoke('downloads:focus', id),
  hostSwitch: (id, index) => ipcRenderer.invoke('downloads:hostSwitch', id, index),
  hostClose: (id) => ipcRenderer.invoke('downloads:hostClose', id),
  hostBrowser: (id) => ipcRenderer.invoke('downloads:hostBrowser', id),
  hostAdopt: (id) => ipcRenderer.invoke('downloads:hostAdopt', id),
  onSourcesChanged: (cb) => ipcRenderer.on('sources:changed', () => cb()),
  onHostOpen: (cb) => ipcRenderer.on('hostview:open', (_e, p) => cb(p)),
  onHostStatus: (cb) => ipcRenderer.on('hostview:status', (_e, p) => cb(p)),
  onHostClose: (cb) => ipcRenderer.on('hostview:close', (_e, p) => cb(p)),
  onDownloads: (cb) => ipcRenderer.on('downloads:changed', (_e, list) => cb(list)),
  onLaunchError: (cb) => ipcRenderer.on('launch:error', (_e, msg) => cb(msg)),
});
